//! Human-readable names for token kinds, used in diagnostics.

use crate::lexer::token::TokenKind;

impl TokenKind {
    /// The source text of the token, for diagnostics.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Module => "module",
            Self::Import => "import",
            Self::Private => "private",
            Self::Struct => "struct",
            Self::Fn => "fn",
            Self::Let => "let",
            Self::Const => "const",
            Self::If => "if",
            Self::Else => "else",
            Self::While => "while",
            Self::For => "for",
            Self::In => "in",
            Self::Return => "return",
            Self::Break => "break",
            Self::Continue => "continue",
            Self::True => "true",
            Self::False => "false",
            Self::Int => "int",
            Self::Float => "float",
            Self::Bool => "bool",
            Self::Char => "char",
            Self::String => "string",
            Self::Void => "void",
            Self::Extern => "extern",
            Self::Export => "export",
            Self::Pin => "pin",
            Self::Panic => "panic",
            Self::Thread => "thread",
            Self::Spawn => "spawn",
            Self::Async => "async",
            Self::Await => "await",
            Self::Send => "send",
            Self::Recv => "recv",
            Self::Mutex => "mutex",
            Self::Defer => "defer",
            Self::Yield => "yield",
            Self::Match => "match",
            Self::Trait => "trait",
            Self::Impl => "impl",
            Self::IntLit => "integer literal",
            Self::FloatLit => "float literal",
            Self::BoolLit => "boolean literal",
            Self::CharLit => "character literal",
            Self::StringLit => "string literal",
            Self::Ident => "identifier",
            Self::Plus => "+",
            Self::Minus => "-",
            Self::Star => "*",
            Self::Slash => "/",
            Self::Percent => "%",
            Self::EqEq => "==",
            Self::NotEq => "!=",
            Self::Lt => "<",
            Self::Gt => ">",
            Self::Le => "<=",
            Self::Ge => ">=",
            Self::AndAnd => "&&",
            Self::OrOr => "||",
            Self::Not => "!",
            Self::Eq => "=",
            Self::LParen => "(",
            Self::RParen => ")",
            Self::LBrace => "{",
            Self::RBrace => "}",
            Self::LBracket => "[",
            Self::RBracket => "]",
            Self::Semi => ";",
            Self::Comma => ",",
            Self::Colon => ":",
            Self::Dot => ".",
            Self::DotDot => "..",
            Self::Arrow => "->",
            Self::Eof => "end of input",
        }
    }
}
